import type { Metadata } from "next";
import { Geist_Mono, Inter, Playfair_Display } from "next/font/google";
import "./globals.css";
import Navbar from "@/components/Navbar";
import ThemeToggle from "@/components/ThemeToggle";

const inter = Inter({
  variable: "--font-inter",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

const playfairDisplay = Playfair_Display({
  variable: "--font-playfair-google",
  subsets: ["latin"],
  display: "swap",
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      className={`${inter.variable} ${geistMono.variable} ${playfairDisplay.variable} h-full antialiased`}
      suppressHydrationWarning={true}
    >
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html: `
              (function() {
                try {
                  var theme = localStorage.getItem('theme');
                  if (!theme) {
                    theme = 'light';
                  }
                  if (theme === 'dark') {
                    document.documentElement.classList.add('dark');
                  } else {
                    document.documentElement.classList.remove('dark');
                  }
                } catch (e) {}

                function isMediaTarget(target) {
                  return !!(target && (target.closest && target.closest('img, picture, svg, canvas, video')));
                }

                document.addEventListener('contextmenu', function (event) {
                  if (isMediaTarget(event.target)) {
                    event.preventDefault();
                  }
                }, { passive: false });

                document.addEventListener('dragstart', function (event) {
                  if (isMediaTarget(event.target)) {
                    event.preventDefault();
                  }
                }, { passive: false });

                document.addEventListener('keydown', function (event) {
                  if ((event.ctrlKey || event.metaKey) && event.key && event.key.toLowerCase() === 's') {
                    var target = event.target;
                    if (isMediaTarget(target)) {
                      event.preventDefault();
                    }
                  }
                });
              })()
            `,
          }}
        />
      </head>
      <body className="min-h-full flex flex-col" suppressHydrationWarning={true}>
        <Navbar />
        <ThemeToggle />
        {children}
      </body>
    </html>
  );
}

